/** Where and how the browser uploads an object (presigned for S3, our API for local). */
export type UploadTarget = {
  method: "PUT";
  url: string;
  /** Headers the browser must send unchanged (they are part of the signature). */
  headers: Record<string, string>;
  expiresAt: string;
};

export type StoredObjectInfo = { sizeBytes: number; contentType: string | null };

/**
 * Object storage for lesson resources and other private files. Objects are
 * private: browsers only ever receive short-lived URLs minted after an
 * authorisation check.
 */
export interface ObjectStorage {
  readonly name: "local" | "s3";
  createUpload(params: {
    key: string;
    contentType: string;
    sizeBytes: number;
    ttlSeconds?: number;
  }): Promise<UploadTarget>;
  createDownloadUrl(params: {
    key: string;
    filename: string;
    contentType: string;
    ttlSeconds?: number;
    /** Binds our own (local) download URLs to the signed-in viewer. */
    viewerId?: string;
  }): Promise<string>;
  head(key: string): Promise<StoredObjectInfo | null>;
  delete(key: string): Promise<void>;
  /** Cheap authenticated call used by the admin "test connection" button. */
  checkConnection(): Promise<{ ok: boolean; detail?: string }>;
}

/** Object keys are generated by the platform (never from user input). */
export const OBJECT_KEY_PATTERN = /^[a-z0-9][a-z0-9/_.-]{0,200}$/;
